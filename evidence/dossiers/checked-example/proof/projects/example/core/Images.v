(** * example / core: the two images

    Each [images/<Build>.v] was generated by the [elf-snapshot] tool of
    linux-process-semantics from the ELF file built by replay/example/build.sh
    (out/core.plain, out/core.asan).  The [_wf] lemmas check by
    computation that each image is well formed ([OssFuzzTheorems.Core.Images]),
    so that no statement about it holds only because the image has no valid
    entry.  Same layout as their projects/pupnp/FuzzHttp/Images.v, two builds. *)

From LinuxProcessSemantics.LinuxProcessSem Require Import MemImageType.
From OssFuzzTheorems.Core Require Import Images.
From OssFuzzTheorems.example.core.images Require Plain Asan.

Definition plain : Image := mkImage Plain.M.loaded_segments Plain.M.init_pc Plain.M.phdrs.
Definition asan : Image := mkImage Asan.M.loaded_segments Asan.M.init_pc Asan.M.phdrs.

Lemma plain_wf : image_wf plain.  Proof. check_image_wf. Qed.
Lemma asan_wf : image_wf asan.  Proof. check_image_wf. Qed.
